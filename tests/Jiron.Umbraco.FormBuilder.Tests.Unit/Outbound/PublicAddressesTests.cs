using System.Net;
using Jiron.Umbraco.FormBuilder.Core.Outbound;

namespace Jiron.Umbraco.FormBuilder.Tests.Unit.Outbound;

/// <summary>
/// Which addresses a call to another host may reach (ADR-0076): only globally reachable ones, each range that is not
/// refused at its edges, and an IPv6 address that carries an IPv4 one judged by that address.
/// </summary>
[TestFixture]
public sealed class PublicAddressesTests
{
    [TestCase("1.1.1.1")]
    [TestCase("8.8.8.8")]
    [TestCase("93.184.215.14")]
    [TestCase("11.0.0.1", Description = "just past 10/8")]
    [TestCase("9.255.255.255", Description = "just before 10/8")]
    [TestCase("100.63.255.255", Description = "just before 100.64/10")]
    [TestCase("100.128.0.1", Description = "just past 100.64/10")]
    [TestCase("126.255.255.255", Description = "just before 127/8")]
    [TestCase("128.0.0.1", Description = "just past 127/8")]
    [TestCase("169.253.255.255", Description = "just before 169.254/16")]
    [TestCase("169.255.0.1", Description = "just past 169.254/16")]
    [TestCase("172.15.255.255", Description = "just before 172.16/12")]
    [TestCase("172.32.0.1", Description = "just past 172.16/12")]
    [TestCase("192.0.1.1", Description = "between 192.0.0/24 and 192.0.2/24")]
    [TestCase("192.88.98.1", Description = "just before 192.88.99/24")]
    [TestCase("192.167.255.255", Description = "just before 192.168/16")]
    [TestCase("192.169.0.1", Description = "just past 192.168/16")]
    [TestCase("198.17.255.255", Description = "just before 198.18/15")]
    [TestCase("198.20.0.1", Description = "just past 198.18/15")]
    [TestCase("198.51.101.1", Description = "just past 198.51.100/24")]
    [TestCase("203.0.112.1", Description = "just before 203.0.113/24")]
    [TestCase("223.255.255.255", Description = "the last unicast address")]
    [TestCase("2606:4700:4700::1111")]
    [TestCase("2a00:1450:4001:82a::200e")]
    [TestCase("2001:200::1", Description = "just past 2001::/23")]
    [TestCase("2001:db9::1", Description = "just past 2001:db8::/32")]
    [TestCase("3ffe:ffff::1", Description = "just before 3fff::/20")]
    [TestCase("::ffff:8.8.8.8", Description = "a public IPv4 address in IPv6 form")]
    [TestCase("64:ff9b::808:808", Description = "NAT64 to a public IPv4 address")]
    [TestCase("2002:808:808::1", Description = "6to4 over a public IPv4 address")]
    public void AGloballyReachableAddress_IsPublic(string address) =>
        Assert.That(PublicAddresses.IsPublic(IPAddress.Parse(address)), Is.True);

    [TestCase("0.0.0.0", Description = "this network")]
    [TestCase("0.255.255.255")]
    [TestCase("10.0.0.1", Description = "private")]
    [TestCase("10.255.255.255")]
    [TestCase("100.64.0.1", Description = "shared address space")]
    [TestCase("100.127.255.255")]
    [TestCase("127.0.0.1", Description = "loopback")]
    [TestCase("127.255.255.254")]
    [TestCase("169.254.169.254", Description = "link-local, where clouds answer with their metadata")]
    [TestCase("169.254.0.1")]
    [TestCase("172.16.0.1", Description = "private")]
    [TestCase("172.31.255.255")]
    [TestCase("192.0.0.8", Description = "protocol assignments")]
    [TestCase("192.0.2.1", Description = "documentation")]
    [TestCase("192.88.99.1", Description = "the old 6to4 relays")]
    [TestCase("192.168.0.1", Description = "private")]
    [TestCase("192.168.255.255")]
    [TestCase("198.18.0.1", Description = "benchmarking")]
    [TestCase("198.19.255.255")]
    [TestCase("198.51.100.1", Description = "documentation")]
    [TestCase("203.0.113.1", Description = "documentation")]
    [TestCase("224.0.0.1", Description = "multicast")]
    [TestCase("240.0.0.1", Description = "reserved")]
    [TestCase("255.255.255.255", Description = "broadcast")]
    [TestCase("::", Description = "unspecified")]
    [TestCase("::1", Description = "loopback")]
    [TestCase("::127.0.0.1", Description = "an IPv4-compatible address, outside global unicast")]
    [TestCase("100::1", Description = "discard only")]
    [TestCase("fe80::1", Description = "link-local")]
    [TestCase("fe80::1%3", Description = "link-local with a zone")]
    [TestCase("fc00::1", Description = "unique local")]
    [TestCase("fd12:3456::1", Description = "unique local")]
    [TestCase("ff02::1", Description = "multicast")]
    [TestCase("4000::1", Description = "outside global unicast")]
    [TestCase("2001::1", Description = "protocol assignments")]
    [TestCase("2001:1ff::1", Description = "the end of 2001::/23")]
    [TestCase("2001:db8::1", Description = "documentation")]
    [TestCase("3fff::1", Description = "documentation")]
    [TestCase("3fff:fff::1")]
    [TestCase("::ffff:127.0.0.1", Description = "loopback in IPv6 form")]
    [TestCase("::ffff:10.0.0.1", Description = "a private address in IPv6 form")]
    [TestCase("::ffff:169.254.169.254", Description = "link-local in IPv6 form")]
    [TestCase("64:ff9b::a00:1", Description = "NAT64 to a private address")]
    [TestCase("64:ff9b::7f00:1", Description = "NAT64 to loopback")]
    [TestCase("2002:a00:1::1", Description = "6to4 over a private address")]
    [TestCase("2002:7f00:1::1", Description = "6to4 over loopback")]
    public void AnAddressThatIsNotGloballyReachable_IsNotPublic(string address) =>
        Assert.That(PublicAddresses.IsPublic(IPAddress.Parse(address)), Is.False);
}
