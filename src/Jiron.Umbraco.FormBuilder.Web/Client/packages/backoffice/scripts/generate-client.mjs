// Generates the management API client (src/api) from the committed OpenAPI snapshot docs/api/jfb.json, never from a
// running site, so the client and the demo never wait on each other (ADR-0001, ADR-0050). The snapshot test writes the
// snapshot; the generated client is committed with it, and generate-client.test.mjs fails when they differ.
//   npm run generate-client -w @jfb/backoffice
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createClient, defaultPlugins } from '@hey-api/openapi-ts';
import { repositoryRoot } from '../../../scripts/version.mjs';

/** The backoffice package's folder. */
export const packageFolder = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The committed snapshot the client is made from. */
export const snapshot = join(repositoryRoot, 'docs', 'api', 'jfb.json');

/** The committed client. */
export const clientFolder = join(packageFolder, 'src', 'api');

const mark = '// @ts-nocheck generated by @hey-api/openapi-ts (scripts/generate-client.mjs)\n';

/**
 * Generates the client from the snapshot into a folder directly below src, where its import of src/hey-api.ts reads
 * the same as in the committed client.
 * @param {string} output
 * @param {{ silent?: boolean }} [options]
 */
export async function generateClient(output, { silent = false } = {}) {
  if (!existsSync(snapshot)) {
    throw new Error('generate-client: docs/api/jfb.json does not exist; the management API snapshot test writes it');
  }

  await createClient({
    input: snapshot,
    output,
    logs: { level: silent ? 'silent' : 'info' },
    // The address and the sign-in come from the backoffice at run time (umbHttpClient.getConfig()), never from the
    // build. The SDK is one function per operation, named after the operation (folderCreate, treeRoot).
    plugins: [
      ...defaultPlugins,
      { name: '@hey-api/client-fetch', runtimeConfigPath: join(packageFolder, 'src', 'hey-api.ts'), baseUrl: false },
    ],
  });

  // The generated code is not written for this package's strict compiler options (exactOptionalPropertyTypes): its
  // files are not checked themselves, and their types still reach the code that uses them. ESLint and Prettier skip
  // them. A character outside ASCII becomes its escape, which reads the same in a string and keeps the files to the
  // repository's text rules (scripts/check-text.mjs).
  for (const file of readdirSync(output, { recursive: true })) {
    const path = join(output, String(file));
    if (!path.endsWith('.ts')) continue;
    const text = readFileSync(path, 'utf8').replace(
      /[\u0080-\uffff]/g,
      (character) => `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`,
    );
    writeFileSync(path, text.startsWith(mark) ? text : mark + text);
  }
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await generateClient(clientFolder);
  console.log('generate-client: wrote src/api');
}
