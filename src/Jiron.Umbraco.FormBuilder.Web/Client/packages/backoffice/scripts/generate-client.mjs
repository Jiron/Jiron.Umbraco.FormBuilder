// Generates the management API client (src/api) from the committed OpenAPI snapshot docs/api/jfb.json, never from a
// running site, so the client and the demo never wait on each other (ADR-0001). The snapshot test of 4.7 writes the
// snapshot; the generated client is committed with it.
//   npm run generate-client -w @jfb/backoffice
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createClient, defaultPlugins } from '@hey-api/openapi-ts';
import { repositoryRoot } from '../../../scripts/version.mjs';

const snapshot = join(repositoryRoot, 'docs', 'api', 'jfb.json');
if (!existsSync(snapshot)) {
  console.error(
    'generate-client: docs/api/jfb.json does not exist yet; the management API snapshot test writes it (4.7)',
  );
  process.exit(1);
}

await createClient({
  input: snapshot,
  output: 'src/api',
  // The address and the sign-in come from the backoffice at run time (umbHttpClient.getConfig()), never from the
  // build. @hey-api/openapi-ts 0.99 resolves runtimeConfigPath from the package folder (the 1.2a sandbox).
  plugins: [
    ...defaultPlugins,
    { name: '@hey-api/client-fetch', runtimeConfigPath: './src/hey-api.ts', baseUrl: false },
    { name: '@hey-api/sdk', asClass: true },
  ],
});

// The generated code is not written for this package's strict compiler options (exactOptionalPropertyTypes): its
// files are not checked themselves, and their types still reach the code that uses them. ESLint and Prettier skip them.
for (const file of readdirSync('src/api', { recursive: true })) {
  const path = join('src/api', String(file));
  if (!path.endsWith('.ts')) continue;
  const text = readFileSync(path, 'utf8');
  if (!text.startsWith('// @ts-nocheck')) {
    writeFileSync(path, `// @ts-nocheck generated by @hey-api/openapi-ts (scripts/generate-client.mjs)\n${text}`);
  }
}
console.log('generate-client: wrote src/api');
